/* ---------------------------------------------------------------------------
   4. センサー値をプロンプト文にする

   AI に渡す 1 回分の入力を組み立てます。
   ここに履歴や時刻を足すこともできますが、Gemini Nano の文脈は
   短いので、入れすぎると溢れます。
   --------------------------------------------------------------------------- */

function buildUserPrompt(telemetry) {
  return `温度 ${telemetry.t}℃ 湿度 ${telemetry.h}%`;
}


/* ---------------------------------------------------------------------------
   5. AI の返事をボードへのコマンドに変換する

   AI の出力キーと、ボードが受け取るコマンドのキーは
   同じである必要はありません。ここで対応づけます。
   --------------------------------------------------------------------------- */

function toBoardCommand(aiResult) {
  const cmd = {};
  if (typeof aiResult.servo === 'number')  cmd.servo  = Math.round(aiResult.servo);
  if (typeof aiResult.status === 'string') cmd.status = aiResult.status;
  if (typeof aiResult.msg === 'string')    cmd.msg    = aiResult.msg;
  // reason は長いのでボードには送らず、ブラウザー側だけで表示します。
  return cmd;
}


