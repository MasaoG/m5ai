/* ---------------------------------------------------------------------------
   1. システムプロンプト — AI に与える役割
   --------------------------------------------------------------------------- */

const SYSTEM_PROMPT = `あなたは室内環境アドバイザーです。
温度と湿度から換気の必要度を判断してください。

- servo:  換気の必要度を 0（不要）〜180（至急）の整数で表す
- status: 状態を次のどれかで表す
          GOOD（快適） / DRY（乾燥） / HUMID（多湿） / HOT（暑い） / COLD（寒い）
- msg:    24文字以内の日本語コメント
- reason: なぜその判断にしたかを60文字以内で

湿度が高い、または気温が高いほど servo の値を大きくしてください。`;


/* ---------------------------------------------------------------------------
   2. 出力スキーマ — AI に返させる JSON の形

   ここが今日いちばん大事な部分です。
   servo の minimum / maximum は、サーボの物理的な可動範囲そのものです。
   「機械の安全範囲を、AI の出力制約として書く」という設計パターンを
   覚えて帰ってください。
   --------------------------------------------------------------------------- */

const RESPONSE_SCHEMA = {
  type: 'object',
  properties: {
    // 数値は範囲で縛る（サーボの可動範囲そのもの）
    servo:  { type: 'integer', minimum: 0, maximum: 180 },

    // 機械が分岐に使う文字列は enum で縛る。
    // ボード側はこの値で STATUS_COLOR の辞書を引いて色を決めます。
    // 自由な文字列だと「やや多湿ぎみ」「humid」「HUMID」が混ざり、
    // 辞書を引けません。
    status: { type: 'string', enum: ['GOOD', 'DRY', 'HUMID', 'HOT', 'COLD'] },

    // 人間が読むだけの文章は自由でよい。
    // ボードの画面にも日本語フォント（AlibabaSans_JP）があります。
    msg:    { type: 'string',  maxLength: 24 },
    reason: { type: 'string',  maxLength: 60 }
  },
  required: ['servo', 'status', 'msg'],
  additionalProperties: false
};


/* ---------------------------------------------------------------------------
   3. 推論パラメーター
   --------------------------------------------------------------------------- */

