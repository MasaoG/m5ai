# 読み解きのポイント
# ===========================================================================
#
# ■ Lチカとは何か
#
#   「LED を光らせること」ではなく「一定の周期で状態を切り替えること」です。
#   あとで扱うサーボの PWM も、考え方はまったく同じです。
#
# ■ setup() と loop() に分かれている理由
#
#   setup() … 準備。1 回だけでよいこと（初期化、明るさの設定）
#   loop()  … 本番。繰り返したいこと
#
#   明るさの設定を loop() に置いても動きますが、毎回同じ値を
#   設定し直すことになります。「1 回でよいことは setup() に」が原則です。
#
# ■ 色の指定は 16 進数
#
#   0x33ff33 は R=0x33, G=0xff, B=0x33 という意味です。
#   ブロックの「palette 緑」がこの値でした。
#
#     0xff0000 赤   0x00ff00 緑   0x0000ff 青
#     0xffffff 白   0x000000 消灯
#
# ■ fill_color() は 10 個まとめて
#
#   1 個ずつ指定したいときは set_color(番号, 色) を使います。
#
# ===========================================================================
# ★注意★ 明るさの上限
# ===========================================================================
#
#   set_brightness() は 0〜100 のパーセントです。
#   12% なら十分明るく、発熱もほとんどありません。
#
#   ただし上げすぎには注意が必要です。
#   SK6812 は 1 個で最大 60mA ほど流れ、10 個を白（0xffffff）で
#   100% 点灯すると約 600mA。Core2 の入力仕様は 5V @ 500mA なので
#   これを超えます。白は R・G・B すべてが点くため、
#   緑単色の 3 倍の電流が流れます。
#
#   これは HO-3 で扱う「サーボの電源を分ける話」と同じ問題です。
#   部品を足すときは、いつも電流を気にする必要があります。
#   今日 2 回出てくるので、覚えて帰ってください。
#
