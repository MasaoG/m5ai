# HO-1  Lチカ（ベース側面の LED バー）
#
# Core2 for AWS のベース（M5GO-Bottom For AWS）には、
# 側面に 10 個のフルカラー LED（SK6812）が入っています。
# すりガラス状の導光材と組み合わさっていて、柔らかく光ります。
#
#   データ線: G25
#   個数:     10 個
#
# G25 はサーボで使う PORT.B（G26）ともセンサーの PORT.A（G32/G33）とも
# ぶつかりません。そのまま使えます。
#
# ---------------------------------------------------------------------------
# UIFlow2 でのブロックの組み方
#
#   1. 左のハードウェア一覧から Built-in Hardware Module → RGB を追加
#   2. setup ブロックに「内蔵ハードウェアの初期化」と「RGB の初期化」を入れる
#   3. RGB の初期化ブロックで  IO = 25 / number = 10 / type = SK6812
#      → rgb25 という変数ができます（変数名は IO 番号から自動で決まります）
#   4. loop ブロックに「輝度を設定」「すべて設定:色」「停止」を並べる
#
# 下のコードは、そうして生成された Python です。
# ---------------------------------------------------------------------------

import os, sys, io
import M5
from M5 import *
import m5ui
import lvgl as lv
from hardware import RGB
import time


page0 = None
rgb25 = None


def setup():
    """最初に 1 回だけ動く"""
    global page0, rgb25

    M5.begin()
    Widgets.setRotation(1)
    m5ui.init()
    page0 = m5ui.M5Page(bg_c=0xffffff)

    # io=25 に SK6812 が 10 個ぶら下がっている、と宣言する
    rgb25 = RGB(io=25, n=10, type="SK6812")

    # 明るさは 0〜100 のパーセントです。
    # 12% で十分明るく、ほとんど発熱しません。
    # ここで 1 回決めれば十分です。loop の中に置くと、
    # 毎回同じ値を設定し直すことになります。
    rgb25.set_brightness(12)


def loop():
    """ずっと繰り返される"""
    global page0, rgb25

    rgb25.fill_color(0x33ff33)      # 緑
    time.sleep_ms(500)
    rgb25.fill_color(0x000000)      # 消灯
    time.sleep_ms(500)


if __name__ == '__main__':
    try:
        setup()
        while True:
            loop()
    except (Exception, KeyboardInterrupt) as e:
        try:
            m5ui.deinit()
            from utility import print_error_msg
            print_error_msg(e)
        except ImportError:
            print("please update to latest firmware")


