import os, sys, io
import M5
from M5 import *
import m5ui
import lvgl as lv
from hardware import RGB
import time


N = 10                      # 左5個 ＋ 右5個
OFF = 0x000000

page0 = None
lblMode = None
lblInfo = None
rgb25 = None

mode = 1
step = 0                    # 各モードの中での進み具合
_t0 = 0                     # モードに入った時刻


# ===========================================================================
# 課題5　バーグラフ（これが本命。HO-2 と HO-3 でそのまま使います）
# ===========================================================================

def bar(percent, color=0x0078ff):
    """0〜100% を、光る個数 0〜10 個で表す。

    ★ max / min で挟んでいる理由 ★
      percent に 120 や -5 が来ても落ちないようにするためです。
      センサーの値をそのまま渡すと、たまに範囲外が来ます。
      ここを省くと IndexError で止まります。
    """
    p = max(0, min(100, percent))
    n = int(p * N / 100 + 0.5)          # +0.5 で四捨五入
    for i in range(N):
        rgb25.set_color(i, color if i < n else OFF)


def clear():
    for i in range(N):
        rgb25.set_color(i, OFF)


def info(text):
    lblInfo.set_text(text)


# ===========================================================================
# setup
# ===========================================================================

def setup():
    global page0, lblMode, lblInfo, rgb25, _t0

    M5.begin()
    Widgets.setRotation(1)
    m5ui.init()

    page0 = m5ui.M5Page(bg_c=0x000000)
    lblMode = m5ui.M5Label("課題1 点滅 100ms", x=20, y=30,
                           text_c=0xffffff, bg_c=0x000000, bg_opa=0,
                           font=lv.AlibabaSans_JP24, parent=page0)
    lblInfo = m5ui.M5Label("--", x=20, y=95,
                           text_c=0xff8c00, bg_c=0x000000, bg_opa=0,
                           font=lv.AlibabaSans_JP24, parent=page0)
    m5ui.M5Label("ボタンC でモード切替", x=20, y=185,
                 text_c=0x888888, bg_c=0x000000, bg_opa=0,
                 font=lv.AlibabaSans_JP24, parent=page0)
    page0.screen_load()

    rgb25 = RGB(io=25, n=N, type="SK6812")
    rgb25.set_brightness(12)
    clear()
    _t0 = time.ticks_ms()
    print('=== HO-1 改造課題 サンプル解答 ===')


MODE_NAME = {
    1: "課題1 点滅 100ms",
    2: "課題2 白で明るさを上げる",
    3: "課題3 流れる光",
    4: "課題4 ボタンAで点灯",
    5: "課題5 バーグラフ",
}


def loop():
    global mode, step, _t0

    M5.update()

    # --- モード切替（ボタン C）---------------------------------------------
    if M5.BtnC.wasPressed():
        mode = mode % 5 + 1
        step = 0
        _t0 = time.ticks_ms()
        rgb25.set_brightness(12)        # 課題2 で上げた明るさを必ず戻す
        clear()
        lblMode.set_text(MODE_NAME[mode])
        print('--- モード', mode, MODE_NAME[mode], '---')
        time.sleep_ms(200)
        return

    # =======================================================================
    # 課題1　点滅間隔を 100 ミリ秒にする
    # =======================================================================
    #
    #   元のコードの time.sleep_ms(500) を 100 にするだけです。
    #   速くすると「点滅」ではなく「チラつき」に見えてきます。
    #   さらに速くして 10ms にすると、人間の目には点きっぱなしに見えます。
    #   ここが「Lチカ＝周期の切り替え」という話の入口です。
    #
    if mode == 1:
        if step == 0:
            rgb25.fill_color(0x33ff33)
            info("点灯")
        else:
            rgb25.fill_color(OFF)
            info("消灯")
        step = 1 - step
        time.sleep_ms(100)

    # =======================================================================
    # 課題2　白にして、明るさを少しずつ上げる
    # =======================================================================
    #
    #   ★ 本体が熱くなったら、すぐボタン C で抜けてください ★
    #
    #   このサンプルは 12 → 100% まで 8段階で上げ、上まで行ったら
    #   自動で 12% に戻します。上げっぱなしにしないための安全策です。
    #
    #   白（0xffffff）は R・G・B の3つすべてが点くので、
    #   緑単色のときの 3倍の電流が流れます。
    #   計算上は 10個 × 60mA = 600mA。Core2 の入力仕様は 500mA です。
    #
    #   ただし実測では落ちませんでした。データシートの 60mA は
    #   「最大値」であって、実際の消費はそれより小さいためです。
    #   計算と実測が食い違うのはよくあることで、
    #   両方を知ったうえで余裕のある値を選ぶのが実務の考え方です。
    #
    elif mode == 2:
        levels = [12, 25, 40, 55, 70, 85, 100]
        if step < len(levels):
            b = levels[step]
            rgb25.set_brightness(b)
            rgb25.fill_color(0xffffff)
            info("明るさ {}%".format(b))
            step += 1
            time.sleep_ms(1200)
        else:
            rgb25.set_brightness(12)
            rgb25.fill_color(0xffffff)
            info("12% に戻しました")
            step = 0
            time.sleep_ms(2500)

    # =======================================================================
    # 課題3　1個ずつ順番に光らせる（流れる光）
    # =======================================================================
    #
    #   ★ ここで覚えてほしいのは「状態を変数で持つ」ことです ★
    #
    #   pos が今どこを光らせているかを覚えていて、
    #   loop が1回まわるたびに1つ進みます。
    #   % N（10 で割った余り）を使うと、9 の次が 0 に戻ります。
    #
    #   逆向きに流したいときは set_color(N - 1 - i, ...) にします。
    #
    elif mode == 3:
        for i in range(N):
            rgb25.set_color(i, 0x33ff33 if i == step else OFF)
        info("位置 {}".format(step))
        step = (step + 1) % N
        time.sleep_ms(80)

    # =======================================================================
    # 課題4　ボタン A を押している間だけ光らせる
    # =======================================================================
    #
    #   ★ isPressed() と wasPressed() の違い ★
    #
    #     isPressed()  … 今 押されているか（押している間ずっと True）
    #     wasPressed() … 押された瞬間だけ True（1回だけ）
    #
    #   「押している間だけ」なので isPressed() を使います。
    #   wasPressed() にすると一瞬しか光りません。
    #
    #   loop の先頭の M5.update() を呼ばないと、ボタンの状態が
    #   いつまでも更新されません。ここを忘れる人が多いです。
    #
    elif mode == 4:
        if M5.BtnA.isPressed():
            rgb25.fill_color(0x33ff33)
            info("ボタンA 押下中")
        else:
            rgb25.fill_color(OFF)
            info("ボタンA を押してください")
        time.sleep_ms(50)

    # =======================================================================
    # 課題5　★本命★ 10個をバーグラフとして使う
    # =======================================================================
    #
    #   ここでは 0 → 100 → 0 を自動で往復させて、動きを見せています。
    #   HO-2 では、この percent のところに湿度を入れます。
    #
    #     while True:
    #         t, h = read_sht30()
    #         bar(h)
    #         time.sleep(1)
    #
    #   これで「画面を見なくても湿度が分かる出力」になります。
    #   アイデアソンで「画面を見なくてもわかる」の制約カードを
    #   引いたチームは、これがそのまま使えます。
    #
    else:
        p = step if step <= 100 else 200 - step
        bar(p, 0x0078ff if p < 70 else 0xff2800)   # 70% 以上は赤に変える
        info("{} %".format(p))
        step = (step + 4) % 200
        time.sleep_ms(60)


if __name__ == '__main__':
    try:
        setup()
        while True:
            loop()
    except (Exception, KeyboardInterrupt) as e:
        try:
            m5ui.deinit()
            from utility import print_error_msg
            print_error_msg(e)
        except ImportError:
            print("please update to latest firmware")


