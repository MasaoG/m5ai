# HO-1 改造課題のサンプル解答（課題1〜5）
#
# ---------------------------------------------------------------------------
# 使いかた
#
#   ★ モードの切り替えは ボタン C（いちばん右）です ★
#   課題4 で「ボタン A を押している間だけ光らせる」をやるので、
#   ボタン A は空けてあります。
#
#   画面に今のモードが出ます。1 → 2 → 3 → 4 → 5 → 1 … と回ります。
#
# ---------------------------------------------------------------------------
# 先に答えを見る前に
#
#   このファイルは「答え合わせ」用です。
#   まず自分で書いてみて、動かなかったとき、あるいは動いたあとに
#   別の書き方を見たくなったときに開いてください。
