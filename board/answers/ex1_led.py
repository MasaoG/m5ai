#
# ■ 明るさの設定を setup() に置くのと loop() に置くのとで、何が違うか
#
#   動作は同じです。違うのは「何回実行されるか」だけ。
#   loop() に置くと、毎秒何十回も同じ値を設定し直すことになります。
#
#   無駄だというだけでなく、あとで「明るさを変える機能」を足したときに、
#   loop() の設定が毎回それを上書きしてしまいます。
#   1回でよいことは setup() に、が原則です。
#
#   このファイルの課題2 では、わざと loop() の中で変えています。
#   「明るさを変えること自体が目的」だからです。
#
# ■ 課題5 の +0.5 は何のためか
#
#   int() は小数点以下を切り捨てます。
#   49% のとき 49 * 10 / 100 = 4.9 → int で 4 個。
#   +0.5 すると 5.4 → 5 個。つまり四捨五入になります。
#
#   切り捨てのままだと、99% でも 9 個しか光りません。
#
# ===========================================================================
# つまずいたら
# ===========================================================================
#
#   IndexError: bytearray index out of range
#     → set_color() の番号が 10 を超えています。0〜9 です。
#       bar() の max/min を消していませんか。
#
#   モードが切り替わらない
#     → loop() の先頭で M5.update() を呼んでいるか確認してください。
#
#   課題2 で本体が熱い
#     → すぐボタン C を押して抜けてください。明るさが 12% に戻ります。
