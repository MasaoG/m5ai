# HO-2  温湿度センサーを読む（ENV Ⅲ / SHT30）
#
# 接続: ENV Ⅲ Unit → PORT.A（本体上部・赤いコネクター）
# Core2 の PORT.A は G32 = SDA / G33 = SCL です。
# ベース側面の PORT.B / PORT.C とは別なので間違えないこと。

from machine import I2C, Pin
import time

i2c = I2C(0, scl=Pin(33), sda=Pin(32), freq=100000)

# --- まずスキャンする ------------------------------------------------------
# コードを書く前に、センサーがバス上に見えているか確認します。
# ここを飛ばすと、配線ミスなのかコードのミスなのか分からなくなります。
#
#   0x44 = SHT30    （温湿度）
#   0x70 = QMP6988  （気圧）
#
# [] が返ったら配線を疑ってください。PORT.B に挿していませんか。

print('scan:', [hex(a) for a in i2c.scan()])

ADDR_SHT30 = 0x44


def read_sht30():
    """温度(℃) と湿度(%) を返す"""
    # 0x2C06 = 単発測定・高精度モード（データシートに書かれているコマンド）
    i2c.writeto(ADDR_SHT30, b'\x2C\x06')

    # 測定が終わるまで待つ。この待ち時間を削ると値が取れません。
    time.sleep_ms(20)

    # 温度2バイト + CRC1 + 湿度2バイト + CRC1 の計6バイト
    d = i2c.readfrom(ADDR_SHT30, 6)

    t_raw = d[0] << 8 | d[1]
    h_raw = d[3] << 8 | d[4]

    # データシートに書かれている変換式
    t = -45 + 175 * t_raw / 65535
    h = 100 * h_raw / 65535
    return t, h


while True:
    t, h = read_sht30()
    print('{:.1f}C  {:.1f}%'.format(t, h))
    time.sleep(1)


